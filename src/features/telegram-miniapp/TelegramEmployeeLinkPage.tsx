import { FormEvent, memo, useMemo, useState } from "react";
import { Link2 } from "lucide-react";

import { Button } from "../../components/ui/button";
import { Checkbox } from "../../components/ui/checkbox";
import { StateMessage } from "../../components/ui/Feedback";
import { Input } from "../../components/ui/input";
import { useI18n } from "../../i18n";
import type { TelegramMiniAppAuthResult } from "./telegramMiniApp.types";
import { notifyTelegram } from "./telegramWebApp";
import { TgField } from "./TelegramUi";

type Props = {
  auth: TelegramMiniAppAuthResult;
  onLink: (token: string) => Promise<void>;
};

function TelegramEmployeeLinkPage({ auth, onLink }: Props) {
  const { tx } = useI18n();
  const [linkToken, setLinkToken] = useState("");
  const [consentAccepted, setConsentAccepted] = useState(false);
  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const displayName = useMemo(
    () =>
      auth.telegramDisplayName ??
      auth.telegramUserName ??
      (auth.telegramUserId ? `Telegram ${auth.telegramUserId}` : tx("Telegram user")),
    [auth.telegramDisplayName, auth.telegramUserId, auth.telegramUserName, tx],
  );

  async function handleSubmit(event: FormEvent) {
    event.preventDefault();
    const token = linkToken.trim().toUpperCase();

    if (!token) {
      setError(tx("Enter the employee link code generated by HR."));
      return;
    }
    if (!consentAccepted) {
      setError(tx("You must accept consent before linking your employee profile."));
      return;
    }

    setSubmitting(true);
    setError(null);
    try {
      await onLink(token);
      notifyTelegram("success");
    } catch (err) {
      notifyTelegram("error");
      setError(err instanceof Error && err.message ? err.message : tx("Unable to link Telegram account."));
    } finally {
      setSubmitting(false);
    }
  }

  return (
    <section className="tg-card">
      <div className="tg-avatar" aria-hidden="true">
        <Link2 size={26} />
      </div>

      <div>
        <h2 className="tg-card__title">{tx("Link Employee Account")}</h2>
        <p className="tg-card__hint">
          {tx("Your Telegram account is verified. Enter the link code from your employee profile to connect it to your company account.")}
        </p>
      </div>

      <dl className="tg-details">
        <div>
          <dt>{tx("Telegram account")}</dt>
          <dd>{displayName}</dd>
        </div>
      </dl>

      <form onSubmit={handleSubmit} className="tg-form">
        <TgField label={tx("HR link code")} required>
          <Input
            value={linkToken}
            onChange={(e) => {
              setLinkToken(e.target.value.toUpperCase());
              if (error) setError(null);
            }}
            placeholder="A7HF-82KQ"
            autoCapitalize="characters"
            autoCorrect="off"
            spellCheck={false}
            disabled={submitting}
            maxLength={32}
          />
        </TgField>

        <label className="tg-consent">
          <Checkbox checked={consentAccepted} onChange={(e) => setConsentAccepted(e.target.checked)} disabled={submitting} />
          <span>
            {tx("I consent to link my Telegram account to my employee profile for attendance, stock requests, approvals and notifications.")}
          </span>
        </label>

        {error ? <StateMessage tone="error">{error}</StateMessage> : null}

        <Button type="submit" className="tg-block" disabled={submitting}>
          {submitting ? tx("Linking...") : tx("Link Employee")}
        </Button>
      </form>

      <p className="tg-muted">
        {tx("Ask HR or your manager to generate a fresh link code from your employee profile. Codes are short-lived and work once.")}
      </p>
    </section>
  );
}

export default memo(TelegramEmployeeLinkPage);
